"use client";

import { useEffect, useRef, useState } from "react";

// Wraps a chart so it draws itself the first time it scrolls into view.
// The CSS keys every chart animation off `.plot.in`.
export function Plot({ children, className = "" }: { children: React.ReactNode; className?: string }) {
  const ref = useRef<HTMLDivElement>(null);
  const [inView, setInView] = useState(false);
  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    if (!("IntersectionObserver" in window)) return setInView(true);
    const io = new IntersectionObserver(
      ([e]) => {
        if (e.isIntersecting) {
          setInView(true);
          io.disconnect();
        }
      },
      { threshold: 0.15, rootMargin: "0px 0px -8% 0px" },
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);
  return (
    <div ref={ref} className={`plot${inView ? " in" : ""} ${className}`.trim()}>
      {children}
    </div>
  );
}
